def test_empty_prefix_results_in_bare_token_hex_group_id() -> None:
    config = Config(consumer_group_id_prefix="")

    with patch("karapace.core.schema_reader.KafkaConsumer") as consumer_cls:
        _create_consumer_from_config(config)

    group_id = consumer_cls.call_args.kwargs["group_id"]
    assert re.fullmatch(r"[0-9a-f]{12}", group_id)
